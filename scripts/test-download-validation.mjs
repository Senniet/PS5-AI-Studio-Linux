import assert from "node:assert/strict";
import {isAllowedDownloadExtension,buildCivitaiDownloadUrl,describeDownloadHTTPError,nextDownloadByteCount} from "../apps/server/download-validation.mjs";
assert.equal(isAllowedDownloadExtension("text","model.gguf"),true);
assert.equal(isAllowedDownloadExtension("text","model.safetensors"),false);
assert.equal(isAllowedDownloadExtension("controlnet","control.pt"),true);
assert.equal(isAllowedDownloadExtension("controlnet","control.pth"),true);
assert.equal(isAllowedDownloadExtension("text","control.pt"),false);
assert.equal(isAllowedDownloadExtension("video_diffusion_models","model.gguf"),true);
assert.equal(isAllowedDownloadExtension("loras","adapter.safetensors"),true);
assert.equal(isAllowedDownloadExtension("loras","adapter.exe"),false);
assert.equal(isAllowedDownloadExtension("loras","no-extension"),false);
assert.equal(buildCivitaiDownloadUrl("civitai",123,"Model","SafeTensor",456),"https://civitai.com/api/download/models/123?type=Model&format=SafeTensor&fileId=456");
assert.equal(buildCivitaiDownloadUrl("civitai-red",123),"https://civitai.red/api/download/models/123");
assert.throws(()=>buildCivitaiDownloadUrl("civitai-attacker",123),/bestemming/);
assert.throws(()=>buildCivitaiDownloadUrl("civitai",0),/bestemming/);
assert.equal(describeDownloadHTTPError(401,0),"Downloadserver HTTP 401 bij downloaden (controleer API-key en toegangsrechten)");
assert.equal(describeDownloadHTTPError(403,2048),"Downloadserver HTTP 403 bij hervatten (controleer API-key en toegangsrechten)");
assert.equal(describeDownloadHTTPError(503,0),"Downloadserver HTTP 503 bij downloaden");
assert.equal(nextDownloadByteCount(100,50,150),150);
assert.throws(()=>nextDownloadByteCount(100,51,150),e=>e.code==="ERR_DOWNLOAD_SIZE_LIMIT");
assert.throws(()=>nextDownloadByteCount(Number.MAX_SAFE_INTEGER,1,Number.MAX_SAFE_INTEGER),e=>e.code==="ERR_DOWNLOAD_SIZE_LIMIT");
console.log("Download validation fixture: 19 assertions passed");
